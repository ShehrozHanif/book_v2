class TestBadgeFormatConversion:
    """Tests for format conversion methods."""

    def test_base64_roundtrip(self, badge_service, achievement_data):
        """Test that base64 string can be converted back to image."""
        # Generate badge as base64
        base64_str = badge_service.generate_badge(achievement_data, format="base64")

        # Decode and verify it's a valid image
        img_bytes = base64.b64decode(base64_str)
        img = Image.open(BytesIO(img_bytes))

        assert img is not None
        assert img.size == (300, 300)

    def test_bytes_to_pil_conversion(self, badge_service, achievement_data):
        """Test that bytes can be converted to PIL Image."""
        # Generate badge as bytes
        img_bytes = badge_service.generate_badge(achievement_data, format="bytes")

        # Convert to PIL Image
        img = Image.open(BytesIO(img_bytes))

        assert img is not None
        assert img.size == (300, 300)
        assert img.format == "PNG"


