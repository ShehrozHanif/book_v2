class TestBadgeGeneration:
    """Tests for basic badge generation."""

    def test_generate_badge_returns_bytes(self, badge_service, achievement_data):
        """Test that generate_badge returns bytes by default."""
        result = badge_service.generate_badge(achievement_data, format="bytes")

        assert result is not None
        assert isinstance(result, bytes)
        assert len(result) > 0

    def test_generate_badge_returns_base64(self, badge_service, achievement_data):
        """Test that generate_badge can return base64 string."""
        result = badge_service.generate_badge(achievement_data, format="base64")

        assert result is not None
        assert isinstance(result, str)
        # Base64 strings contain only alphanumeric, +, /, and =
        assert all(c in "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/=" for c in result)

    def test_generate_badge_returns_pil_image(self, badge_service, achievement_data):
        """Test that generate_badge can return PIL Image."""
        result = badge_service.generate_badge(achievement_data, format="pil")

        assert result is not None
        assert isinstance(result, Image.Image)
        assert result.size == (300, 300)

    def test_generate_badge_size(self, badge_service, achievement_data):
        """Test that badge has correct dimensions."""
        result = badge_service.generate_badge(achievement_data, format="pil")

        assert result.width == 300
        assert result.height == 300

    def test_generate_badge_png_format(self, badge_service, achievement_data):
        """Test that generated bytes are valid PNG."""
        result = badge_service.generate_badge(achievement_data, format="bytes")

        # PNG files start with these magic bytes
        assert result[:8] == b'\x89PNG\r\n\x1a\n'

    def test_generate_badge_default_format(self, badge_service, achievement_data):
        """Test that default format is bytes."""
        result1 = badge_service.generate_badge(achievement_data)
        result2 = badge_service.generate_badge(achievement_data, format="bytes")

        assert type(result1) == type(result2)
        assert result1 == result2


