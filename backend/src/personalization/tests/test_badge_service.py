class TestRarityColors:
    """Tests for rarity color configuration."""

    def test_rarity_colors_complete(self):
        """Test that all rarity colors are defined."""
        expected_rarities = ["common", "uncommon", "rare", "epic", "legendary"]

        for rarity in expected_rarities:
            assert rarity in RARITY_COLORS

    def test_rarity_colors_structure(self):
        """Test that rarity colors have correct structure."""
        required_fields = ["bg", "border", "text"]

        for rarity, colors in RARITY_COLORS.items():
            for field in required_fields:
                assert field in colors
                # Verify it's a valid hex color
                assert colors[field].startswith("#")
                assert len(colors[field]) == 7  # #RRGGBB format
