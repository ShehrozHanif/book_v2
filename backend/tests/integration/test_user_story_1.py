@pytest.mark.asyncio
async def test_user_story_1_complete_flow(
    chat_service,
    mock_embedding_service,
    mock_retrieval_service,
    mock_generation_service
):
    """
    TEST 2: User Story 1 Complete Flow - Main MVP Test

    Scenario:
    1. Student selects text from textbook
    2. Student asks "What is ROS 2?"
    3. System retrieves relevant passages
    4. System generates answer with citations
    5. Student sees response with [Chapter X: Section Y]

    Acceptance Criteria:
    - Query embedded to 1536 dimensions
    - Passages retrieved from Qdrant
    - Response generated with citations
    - Processing time < 3 seconds (SLA)
    - Relevance scores > 0.85 (SC-005)
    - All services called in correct order
    """
    query = "What is ROS 2?"

    response = await chat_service.process_query(query)

    # Validate response structure
    assert isinstance(response, ChatResponse)
    assert response.response is not None
    assert len(response.response) > 0

    # Validate retrieved passages
    assert len(response.retrieved_passages) == 3
    assert "ROS 2" in response.retrieved_passages[0]

    # Validate relevance scores
    assert len(response.relevance_scores) == 3
    assert all(score > 0.85 for score in response.relevance_scores)

    # Validate citations present
    assert "[Chapter" in response.response
    assert "[Chapter 1:" in response.response

    # Validate SLA: <3 seconds
    assert response.processing_time_ms < 3000
    assert response.processing_time_ms > 0

    # Verify all services were called
    mock_embedding_service.embed_query.assert_called_once_with(query)
    mock_retrieval_service.retrieve_context.assert_called_once()
    mock_generation_service.generate_response.assert_called_once()

    # Verify embedding is 1536 dimensions
    call_args = mock_retrieval_service.retrieve_context.call_args
    assert "query_vector" in call_args.kwargs
    assert len(call_args.kwargs["query_vector"]) == 1536


